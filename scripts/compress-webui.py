"""Generate deterministic gzip assets from the editable embedded HTML."""
from pathlib import Path
import gzip
import json
import re

PALETTE_ROLES = ("background", "surface", "surfaceAlt", "accent", "accentSoft",
                 "text", "muted", "positive", "negative", "warning")
THEME_MARKER = "/*DEVICE_THEME_PRESETS*/ []"


def load_palettes(source_path):
    palettes = json.loads((Path(source_path).parent / "device-themes.json").read_text())["palettes"]
    for index, palette in enumerate(palettes):
        if palette["id"] != index or palette["mode"] not in ("dark", "light"):
            raise ValueError("Theme IDs must be sequential and modes must be dark/light")
        if set(palette["colors"]) != set(PALETTE_ROLES):
            raise ValueError("Theme color roles missing: " + palette["label"])
        for color in palette["colors"].values():
            if re.fullmatch(r"#[0-9A-Fa-f]{6}", color) is None:
                raise ValueError("Invalid theme color: " + color)
    return palettes


def display_hex(color):
    red, green, blue = (int(color[index:index + 2], 16) for index in (1, 3, 5))
    return "#%02X%02X%02X" % ((red >> 3) * 255 // 31, (green >> 2) * 255 // 63, (blue >> 3) * 255 // 31)


def expand_webui(source_path):
    source = Path(source_path).read_text(encoding="utf-8")
    labels = [{"value": palette["id"], "label": palette["label"],
               "family": palette["family"], "mode": palette["mode"],
               "tones": [display_hex(palette["colors"][role]) for role in ("background", "surface", "accent")],
               "text": display_hex(palette["colors"]["text"])} for palette in load_palettes(source_path)]
    if source.count(THEME_MARKER) != 1:
        raise ValueError("Theme placeholder missing or duplicated")
    return source.replace(THEME_MARKER, json.dumps(labels, separators=(",", ":")).replace("<", "\\u003c"))


def write_if_changed(output_path, content):
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)


def generate(source_path, output_path):
    source = expand_webui(source_path)
    palette_lines = ["// Generated from src/device-themes.json.", "#pragma once",
                     "const ThemePalette kThemes[] = {"]
    for palette in load_palettes(source_path):
        palette_lines.append("    { // " + palette["label"])
        for role in PALETTE_ROLES:
            color = palette["colors"][role]
            rgb = ", ".join(str(int(color[index:index + 2], 16)) for index in (1, 3, 5))
            palette_lines.append("        rgb565(" + rgb + "),")
        palette_lines.append("    },")
    palette_lines.extend(["};", 'static_assert(sizeof(kThemes) / sizeof(kThemes[0]) == DASHBOARD_THEME_COUNT, "Theme count mismatch");'])
    write_if_changed(Path(output_path).parent / "device_theme_palettes.h", "\n".join(palette_lines) + "\n")
    lines = ["// Generated by scripts/compress-webui.py; edit src/webui.h instead.",
             "#pragma once", "#include <Arduino.h>"]
    for name in ("index_html", "ota_html"):
        match = re.search(r"const char " + name + r'\[\] PROGMEM = R"rawliteral\(([\s\S]*?)\)rawliteral";', source)
        if match is None:
            raise ValueError("Embedded HTML missing: " + name)
        data = gzip.compress(match.group(1).encode("utf-8"), compresslevel=9, mtime=0)
        lines.append("const uint8_t " + name + "_gzip[] PROGMEM = {")
        for offset in range(0, len(data), 16):
            lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
        lines.append("};")
    content = "\n".join(lines) + "\n"
    write_if_changed(output_path, content)


Import("env")
asset_dir = Path(env.subst("$BUILD_DIR")) / "generated"
generate(Path(env.subst("$PROJECT_DIR")) / "src/webui.h", asset_dir / "webui_gzip.h")
env.Append(CPPPATH=[str(asset_dir)])
