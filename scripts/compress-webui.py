"""Generate deterministic gzip assets from the editable embedded HTML."""
from pathlib import Path
import gzip
import re


def generate(source_path, output_path):
    source = Path(source_path).read_text(encoding="utf-8")
    lines = ["// Generated by scripts/compress-webui.py; edit src/webui.h instead.",
             "#pragma once", "#include <Arduino.h>"]
    for name in ("index_html", "ota_html"):
        match = re.search(r"const char " + name + r'\[\] PROGMEM = R"rawliteral\(([\s\S]*?)\)rawliteral";', source)
        if match is None:
            raise ValueError("Embedded HTML missing: " + name)
        data = gzip.compress(match.group(1).encode("utf-8"), compresslevel=9, mtime=0)
        lines.append("const uint8_t " + name + "_gzip[] PROGMEM = {")
        for offset in range(0, len(data), 16):
            lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
        lines.append("};")
    content = "\n".join(lines) + "\n"
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)


Import("env")
asset_dir = Path(env.subst("$BUILD_DIR")) / "generated"
generate(Path(env.subst("$PROJECT_DIR")) / "src/webui.h", asset_dir / "webui_gzip.h")
env.Append(CPPPATH=[str(asset_dir)])
